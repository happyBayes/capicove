"""Thirty frozen metadata judgments exercise ranking, not model accuracy.

Ten authored lane-response scenarios each run at three independent timeline
positions. Relevance labels are specified below, never generated by the ranking
implementation. No images, videos, transcripts or model outputs are claimed.
"""

from dataclasses import dataclass, replace

import pytest

from capicove.contracts import (
    CharacterRange,
    SearchableUnit,
    TargetType,
    TemporalRange,
    TextChunkLocator,
    TextOrigin,
)
from capicove.retrieval.temporal import TemporalCandidateAssembler, temporal_iou
from capicove.retrieval.video_fusion import CandidateLane, VideoCandidate, weighted_video_rrf
from tests.unit.retrieval.test_video_models import unit


@dataclass(frozen=True)
class Judgment:
    name: str
    lanes: tuple[tuple[str, tuple[str, ...]], ...]
    expected: tuple[str, ...]
    keyframes: bool = False


JUDGMENTS = (
    Judgment("text-keyframe", (("keyframe_visual", ("k1", "k2")),), ("k1", "k2"), True),
    Judgment("image-keyframe", (("keyframe_visual", ("k2", "k1")),), ("k2", "k1"), True),
    Judgment("text-segment", (("segment_visual", ("s1", "s2")),), ("s1", "s2")),
    Judgment("image-segment", (("keyframe_visual", ("k2",)),), ("s2",)),
    Judgment("asr-only", (("asr_lexical", ("asr1",)),), ("s1",)),
    Judgment("ocr-only", (("ocr_lexical", ("ocr2",)),), ("s2",)),
    Judgment(
        "complementary-fusion",
        (("segment_visual", ("s1", "s2")), ("asr_lexical", ("asr2",))),
        ("s2", "s1"),
    ),
    Judgment(
        "repeated-frame-cannot-inflate-lane",
        (("keyframe_visual", ("k1", "k1b", "k1c")), ("segment_visual", ("s2",))),
        ("s1", "s2"),
    ),
    Judgment("overlap-deduplication", (("segment_visual", ("s1", "s1overlap")),), ("s1",)),
    Judgment("source-isolation", (("segment_visual", ("s1", "other")),), ("s1", "other")),
)


class MetadataCatalog:
    """A deliberately small immutable authored timeline and relation fixture."""

    unit_manifest_sha256 = "b" * 64

    def __init__(self, offset: int) -> None:
        self.units: dict[str, SearchableUnit] = {}
        for name, start, end, artifact in (
            ("s1", 0, 10_000, "video-a"),
            ("s1overlap", 500, 10_000, "video-a"),
            ("s2", 10_000, 20_000, "video-a"),
            ("other", 0, 10_000, "video-b"),
        ):
            self.units[name] = replace(
                unit(name, TargetType.VIDEO_SEGMENT),
                artifact_ref=artifact,
                time_range=TemporalRange(start + offset, end + offset),
            )
        for name, timestamp in (("k1", 1000), ("k1b", 2000), ("k1c", 3000), ("k2", 11000)):
            self.units[name] = replace(
                unit(name),
                artifact_ref="video-a",
                timestamp_ms=timestamp + offset,
                scene_range=None,
            )
        for name, origin, start in (
            ("asr1", TextOrigin.ASR, 1000),
            ("asr2", TextOrigin.ASR, 11000),
            ("ocr2", TextOrigin.OCR, 11000),
        ):
            key = self.units["k1"]
            self.units[name] = SearchableUnit(
                name,
                TargetType.TEXT_CHUNK,
                key.source_hash,
                key.artifact_ref,
                f"evidence:{name}",
                (f"representation:{name}",),
                "run",
                "v1",
                key.processing_fingerprint,
                text_locator=TextChunkLocator(
                    origin,
                    CharacterRange(0, 10),
                    time_range=TemporalRange(start + offset, start + offset + 1000),
                ),
            )

    def get(self, unit_id: str) -> SearchableUnit | None:
        return self.units.get(unit_id)

    def get_many(self, unit_ids: tuple[str, ...]) -> tuple[SearchableUnit, ...]:
        return tuple(self.units[key] for key in unit_ids)

    def segments_for_keyframe(self, unit_id: str) -> tuple[str, ...]:
        return ("s2",) if unit_id == "k2" else ("s1",)

    def segments_for_keyframes(self, unit_ids: tuple[str, ...]) -> dict[str, tuple[str, ...]]:
        return {key: self.segments_for_keyframe(key) for key in unit_ids}

    def segments_for_text(self, unit_id: str) -> tuple[tuple[str, int], ...]:
        return (("s1" if unit_id == "asr1" else "s2", 1000),)

    def segments_for_texts(
        self, unit_ids: tuple[str, ...]
    ) -> dict[str, tuple[tuple[str, int], ...]]:
        return {key: self.segments_for_text(key) for key in unit_ids}


@pytest.mark.parametrize("offset", (0, 20_000, 40_000), ids=("opening", "middle", "closing"))
@pytest.mark.parametrize("judgment", JUDGMENTS, ids=lambda item: item.name)
def test_authored_metadata_query(judgment: Judgment, offset: int) -> None:
    catalog = MetadataCatalog(offset)
    lanes = tuple(
        CandidateLane(
            lane,
            1.0,
            tuple(
                VideoCandidate(
                    key,
                    catalog.units[key].unit_type,
                    lane,
                    float(1000 - rank) if lane.endswith("lexical") else 0.5 / rank,
                    rank,
                    "authored-fixture",
                    "generation",
                    "fixture-score",
                )
                for rank, key in enumerate(keys, 1)
            ),
        )
        for lane, keys in judgment.lanes
    )
    fused = weighted_video_rrf(lanes)
    if judgment.keyframes:
        assert tuple(item.unit_id for item in fused) == judgment.expected
    else:
        results = TemporalCandidateAssembler(catalog).assemble(fused=fused)
        assert tuple(item.unit.unit_id for item in results) == judgment.expected
        assert (
            temporal_iou(results[0].unit.time_range, catalog.units[judgment.expected[0]].time_range)
            == 1
        )


def test_authored_judgment_inventory_is_frozen() -> None:
    assert len(JUDGMENTS) == 10
    assert len({item.name for item in JUDGMENTS}) == 10
